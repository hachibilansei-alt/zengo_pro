def _font(size: int):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
    ]
    for path in candidates:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size=size)
            except Exception:
                pass
    return ImageFont.load_default()


def make_poster(title: str, kind: str, score: float, idx: int) -> str:
    """Generate a simple cinematic poster and return static URL path."""
    w, h = 400, 600
    seed = int(hashlib.md5(f"{kind}-{title}-{idx}".encode()).hexdigest()[:8], 16)
    bg, accent, accent2 = PALETTES[seed % len(PALETTES)]
    img = Image.new("RGB", (w, h), bg)
    draw = ImageDraw.Draw(img)

    # gradient-like bands
    for y in range(h):
        t = y / h
        r = int(bg[0] * (1 - t) + accent[0] * t * 0.35)
        g = int(bg[1] * (1 - t) + accent[1] * t * 0.35)
        b = int(bg[2] * (1 - t) + accent[2] * t * 0.35)
        draw.line([(0, y), (w, y)], fill=(r, g, b))

    # decorative circles
    draw.ellipse([w - 180, -80, w + 60, 160], outline=accent + (0,), width=3)
    draw.ellipse([-60, h - 200, 160, h + 40], outline=accent2, width=2)

    # top label
    label = "GAME" if kind == "game" else "FILM"
    font_sm = _font(18)
    font_title = _font(28)
    font_score = _font(36)
    draw.rounded_rectangle([20, 24, 110, 52], radius=12, fill=accent)
    draw.text((36, 30), label, fill=(255, 255, 255), font=font_sm)

    # title wrapped
    words = title.split()
    lines, cur = [], ""
    for word in words:
        test = (cur + " " + word).strip()
        # approximate width
        if len(test) > 14:
            if cur:
                lines.append(cur)
            cur = word
        else:
            cur = test
    if cur:
        lines.append(cur)
    lines = lines[:5]
    y0 = 220 - (len(lines) - 1) * 16
    for i, line in enumerate(lines):
        # center-ish for RTL feel: right aligned-ish
        bbox = draw.textbbox((0, 0), line, font=font_title)
        tw = bbox[2] - bbox[0]
        x = max(24, (w - tw) // 2)
        draw.text((x, y0 + i * 36), line, fill=(245, 245, 250), font=font_title)

    # score badge
    draw.ellipse([w // 2 - 40, h - 120, w // 2 + 40, h - 40], fill=accent)
    score_txt = f"{score:.1f}"
    bbox = draw.textbbox((0, 0), score_txt, font=font_score)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    draw.text(((w - tw) // 2, h - 108), score_txt, fill=(255, 255, 255), font=font_score)

    draw.text((24, h - 28), "ZENGO", fill=accent2, font=font_sm)

    filename = f"poster_{kind}_{idx:03d}.jpg"
    path = UPLOAD / filename
    img.save(path, "JPEG", quality=88, optimize=True)
    return f"/static/uploads/{filename}"


def ensure_schema(conn: sqlite3.Connection) -> None:
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS reviews (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            kind TEXT NOT NULL CHECK(kind IN ('film','game')),
            genre TEXT NOT NULL DEFAULT 'متفرقه',
            year TEXT DEFAULT '',
            score REAL NOT NULL DEFAULT 7.0,
            poster TEXT DEFAULT '',
            platform TEXT DEFAULT '',
            summary TEXT NOT NULL,
            body TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """
    )
    columns = {row[1] for row in conn.execute("PRAGMA table_info(reviews)").fetchall()}
    alters = {
        "images": "ALTER TABLE reviews ADD COLUMN images TEXT NOT NULL DEFAULT '[]'",
        "country": "ALTER TABLE reviews ADD COLUMN country TEXT NOT NULL DEFAULT ''",
        "film_type": "ALTER TABLE reviews ADD COLUMN film_type TEXT NOT NULL DEFAULT 'cinema'",
        "game_device": "ALTER TABLE reviews ADD COLUMN game_device TEXT NOT NULL DEFAULT 'computer'",
        "trailer": "ALTER TABLE reviews ADD COLUMN trailer TEXT NOT NULL DEFAULT ''",
        "content_type": "ALTER TABLE reviews ADD COLUMN content_type TEXT NOT NULL DEFAULT 'review'",
        "author": "ALTER TABLE reviews ADD COLUMN author TEXT NOT NULL DEFAULT 'تحریریه Zengo'",
        "meta_description": "ALTER TABLE reviews ADD COLUMN meta_description TEXT NOT NULL DEFAULT ''",
        "updated_at": "ALTER TABLE reviews ADD COLUMN updated_at TIMESTAMP",
    }
    for col, sql in alters.items():
        if col not in columns:
            conn.execute(sql)


